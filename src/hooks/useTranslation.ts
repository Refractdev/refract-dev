type DictionaryType = typeof dictionary.en

export function useTranslation() {
  const { profile } = useAuth()
  const currentLang = profile?.language ?? 'en'
  const lang = (dictionary[currentLang] ? currentLang : 'en') as keyof typeof dictionary

  const t = useCallback(
    (key: string, variables?: Record<string, string>): string => {
      const keys = key.split('.')
      let current: any = dictionary[lang]

      for (const k of keys) {
        if (current === undefined || current === null) {
          // Fallback to English
          let enCurrent: any = dictionary.en
          for (const k2 of keys) {
            enCurrent = enCurrent?.[k2]
          }
          current = enCurrent
          break
        }
        current = current[k]
      }

      if (typeof current !== 'string') {
        return key
      }

      let text = current
      if (variables) {
        Object.entries(variables).forEach(([k, val]) => {
          text = text.replace(`{${k}}`, val)
        })
      }

      return text
    },
    [lang]
  )

  return { t, lang }
}
